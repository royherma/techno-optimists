// Local-only browser regression: real auth, R2 uploads, publishing and reload.
// PLAYWRIGHT_PATH may point to a shared installation; no production writes.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdir, readFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_PATH ?? 'playwright')
const base = process.env.TO_BASE ?? 'http://localhost:8797'
assert(['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Local hosts only')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const auth = await context.request.post(`${base}/api/auth/request`, { data: { email: `media-qa-${Date.now()}@example.test` } })
  assert.equal(auth.status(), 200)
  const { dev_link } = await auth.json()
  assert(dev_link)
  await page.goto(dev_link)
  const created = await context.request.post(`${base}/api/challenges`, { data: { type: 'problem', title: `Discussion media check ${Date.now()}`, summary: 'Local-only fixture for checking collaborative image and video responses.' } })
  assert.equal(created.status(), 201, await created.text())
  const { challenge } = await created.json()
  const url = `${base}/c/${challenge.slug}#discussion`
  await page.goto(url)
  await page.getByRole('button', { name: 'Publish response', exact: true }).waitFor()
  await page.locator('#response-body').fill('Compare **water clarity** before and after.\n\nhttps://example.org/research')
  await page.getByRole('button', { name: 'Formatting', exact: true }).click()
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  assert.equal(await page.locator('.composer-preview strong').textContent(), 'water clarity')
  assert.equal(await page.locator('.composer-preview a').getAttribute('href'), 'https://example.org/research')
  await page.getByRole('button', { name: 'Write', exact: true }).click()
  await mkdir('outputs/discussion-media', { recursive: true })
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'color=c=lightblue:s=320x180:d=1', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', 'outputs/discussion-media/sample.mp4'])
  const video = { name: 'sample.mp4', mimeType: 'video/mp4', buffer: await readFile('outputs/discussion-media/sample.mp4') }
  const png = { name: 'sample.png', mimeType: 'image/png', buffer: await readFile(new URL('../apps/web/public/seed/pond-s-oxygen-crashes-at-dawn.png', import.meta.url)) }
  await page.locator('input[type=file]').setInputFiles(png)
  await page.locator('.composer-attachments img').waitFor()
  await page.getByLabel('Description', { exact: true }).fill('Water clarity sample')
  await page.reload()
  await page.locator('.composer-attachments img').waitFor()
  assert.equal(await page.getByLabel('Description', { exact: true }).inputValue(), 'Water clarity sample')
  await page.getByRole('button', { name: 'Publish response', exact: true }).click()
  await page.getByText('Your response is published.', { exact: true }).waitFor()
  await page.locator('.discussion-list img').waitFor()
  assert.equal(await page.locator('.discussion-list img').getAttribute('alt'), 'Water clarity sample')
  await page.locator('.discussion-list img').scrollIntoViewIfNeeded()
  await page.waitForFunction(() => { const img = document.querySelector('.discussion-list img'); return img?.complete && img.naturalWidth > 0 })
  await page.locator('input[type=file]').setInputFiles(video)
  await page.locator('.composer-attachments video').waitFor()
  await page.getByRole('button', { name: 'Publish response', exact: true }).click()
  await page.locator('.discussion-list video').waitFor()
  await page.waitForFunction(() => document.querySelector('.discussion-list video')?.readyState >= 1)
  await page.reload()
  await page.locator('.discussion-list img').waitFor()
  assert.equal(await page.locator('.discussion-list .response-rich strong').first().textContent(), 'water clarity')
  await page.locator('#response-body').fill('<script>alert(1)</script>\n\n[unsafe](javascript:alert)\n\n![remote](https://example.org/tracker.png)')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  assert.equal(await page.locator('.composer-preview script, .composer-preview img, .composer-preview a[href^="javascript:"]').count(), 0)
  await page.getByRole('button', { name: 'Write', exact: true }).click()
  await page.locator('#response-body').fill('A useful follow-up observation.')
  await page.locator('input[type=file]').setInputFiles(Array.from({ length: 5 }, (_, i) => ({ ...png, name: `${i}.png` })))
  await page.getByText('Attach up to 4 files per response.', { exact: true }).waitFor()
  await page.locator('input[type=file]').setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
  await page.getByText('Choose JPG, PNG, WebP, HEIC, MP4, MOV or WebM files, up to 100 MB each.', { exact: true }).waitFor()
  // Request failure must preserve the written draft.
  await page.route('**/api/uploads', (route) => route.fulfill({ status: 503, body: '{}' }))
  await page.locator('input[type=file]').setInputFiles(png)
  await page.getByRole('alert').filter({ hasText: 'Could not upload sample.png.' }).waitFor()
  assert(await page.getByRole('button', { name: 'Publish response', exact: true }).isDisabled())
  assert.equal(await page.locator('#response-body').inputValue(), 'A useful follow-up observation.')
  await page.unroute('**/api/uploads')
  await page.locator('input[type=file]').setInputFiles(png)
  await page.locator('.composer-attachments img').waitFor()
  await page.getByRole('button', { name: 'Add link', exact: true }).click()
  await page.getByLabel('Link URL', { exact: true }).fill('https://example.org/field-test')
  await page.getByLabel('Link text (optional)', { exact: true }).fill('Field notes')
  await page.getByRole('button', { name: 'Insert link', exact: true }).click()
  assert((await page.locator('#response-body').inputValue()).includes('[Field notes](https://example.org/field-test)'))
  await page.getByRole('button', { name: 'Formatting', exact: true }).click()
  await mkdir('outputs/discussion-media', { recursive: true })
  for (const width of [1440, 1024, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.locator('#discussion').scrollIntoViewIfNeeded()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `No overflow at ${width}`)
    await page.screenshot({ path: `outputs/discussion-media/${width}.png` })
  }
  assert.deepEqual(errors, [])
  console.log('PASS: real image/video uploads, published media-only video, reload, draft recovery, formatting, links, unsafe content, attachment cap, invalid type, upload failure/retry, and responsive layouts.')
} finally { await browser.close() }
